"""Монголын засаг захиргааны нэгж: хүргэлтийн хаяг, бүсийн үнийн суурь. Web-ийн
`features/account/mongolia.ts`-тэй ижил жагсаалт (өөрчлөхдөө хоёуланг нь шинэчилнэ)."""

CAPITAL = "Улаанбаатар"

# 21 аймаг + нийслэл; нэрийг хаягт хадгалах түлхүүр болгон ашиглана.
AIMAGS: tuple[str, ...] = (
    "Архангай",
    "Баян-Өлгий",
    "Баянхонгор",
    "Булган",
    "Говь-Алтай",
    "Говьсүмбэр",
    "Дархан-Уул",
    "Дорноговь",
    "Дорнод",
    "Дундговь",
    "Завхан",
    "Орхон",
    "Өвөрхангай",
    "Өмнөговь",
    "Сүхбаатар",
    "Сэлэнгэ",
    "Төв",
    "Увс",
    "Ховд",
    "Хөвсгөл",
    "Хэнтий",
)
REGIONS: tuple[str, ...] = (CAPITAL, *AIMAGS)

# Нийслэлийн 9 дүүрэг: нийслэлд хүргэлтийн хаяг заавал эдгээрийн нэгээр тодорхойлогдоно.
CAPITAL_DISTRICTS: tuple[str, ...] = (
    "Баянгол",
    "Баянзүрх",
    "Сонгинохайрхан",
    "Сүхбаатар",
    "Хан-Уул",
    "Чингэлтэй",
    "Налайх",
    "Багануур",
    "Багахангай",
)


def is_capital(region: str | None) -> bool:
    return region == CAPITAL


def check_region_and_district(region: str, district: str) -> None:
    """Аймаг/хот жагсаалтад байх, нийслэл бол дүүрэг жагсаалтад байх ёстой. Буруу бол ValueError."""
    if region not in REGIONS:
        raise ValueError("Аймаг, хотыг жагсаалтаас сонгоно уу.")
    if is_capital(region) and district not in CAPITAL_DISTRICTS:
        raise ValueError("Нийслэлийн дүүргийг жагсаалтаас сонгоно уу.")
